_MAX_MEMORY = 4000
_MAX_LITERATURE = 6000
_MAX_CODE_SNIPPET = 1500
_MAX_LOG_LINES = 50
_MAX_STEP_FILE = 12000
_MAX_MODEL_CARD = 6000
_MAX_CONTRACT = 4000

