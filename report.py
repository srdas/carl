def _read_capped(path: Path, max_chars: int) -> str:
    """Read a text file, capping at max_chars."""
    try:
        text = path.read_text()
        if len(text) > max_chars:
            return text[:max_chars] + "\n...(truncated)"
        return text
    except (OSError, UnicodeDecodeError):
        return ""


def is_checkpoint_dupe(path: Path) -> bool:
    """Return whether a path is a Jupyter autosave duplicate."""
    return "-checkpoint" in path.stem


def find_session_plots(session_dir: Path) -> list[Path]:
    """Find all .png plot files in the session's code/ and results/ dirs.

    Recurses so plots written under code/experiments/<run>/ are found, and
    filters out Jupyter checkpoint duplicates (*-checkpoint.png). Shared with
    revisit.discover_artifacts so the report and Step 10 see the same set.
    """
    plots: list[Path] = []
    for subdir in ("code", "results"):
        d = Path(session_dir) / subdir
        if d.exists():
            plots.extend(
                p for p in sorted(d.rglob("*.png"))
                if not is_checkpoint_dupe(p)
            )
    return plots


# Backwards-compatible alias for existing report.py call sites.
_find_plots = find_session_plots


def find_artifact_dirs(session_dir: Path) -> list[Path]:
    """Find shippable artifact/ bundles under the session's code/ tree.

    A session has code/artifact/ after Step 9; a revisit adds
    code/revisit_N/artifact/. Newest last, so the caller can prefer the
    most recent bundle.
    """
    code_dir = Path(session_dir) / "code"
    if not code_dir.exists():
        return []
    return [
        d for d in sorted(code_dir.rglob("artifact"))
        if d.is_dir() and not is_checkpoint_dupe(d)
    ]


def gather_artifact_context(session_dir: Path) -> dict:
    """Collect the artifact bundle's human-readable metadata, if present.

    Returns {} when no bundle exists (sessions predating make_artifact.py),
    so callers can treat the artifact section as optional.
    """
    dirs = find_artifact_dirs(session_dir)
    if not dirs:
        return {}
    artifact_dir = dirs[-1]
    ctx: dict = {"path": str(artifact_dir.relative_to(Path(session_dir)))}

    card = artifact_dir / "MODEL_CARD.md"
    if card.exists():
        ctx["model_card"] = _read_capped(card, _MAX_MODEL_CARD)

    contract = artifact_dir / "contract.json"
    if contract.exists():
        ctx["contract"] = _read_capped(contract, _MAX_CONTRACT)

    ctx["entry_points"] = [
        f.name for f in sorted(artifact_dir.iterdir())
        if f.is_file() and f.suffix in (".py", ".pt", ".json", ".md")
    ]
    return ctx


def _describe_plot(client, model: str, plot_path: Path, memory: str,
                   benchmark_context: str = "") -> dict:
    """Send a plot image to the LLM and get a factual description.

    Returns {filename, label, description}.
    """
    image_bytes = plot_path.read_bytes()
    label = f"fig:{plot_path.stem}"

    benchmark_note = (
        "\n\nIf the figure shows an analytical benchmark / reference solution "
        "(e.g. a Merton optimal fraction, a closed-form policy, a theoretical "
        "curve, an oracle trajectory), you MUST state EXPLICITLY what relation "
        "or formula is being plotted for that benchmark, using the context "
        "below. Name the exact variable or expression shown on each axis and "
        "the formula that defines the benchmark curve. Do not just say "
        "'analytical benchmark' — cite the specific relation (e.g. "
        "'$\\pi^* = (\\mu - r)/(\\gamma \\sigma^2)$').\n\n"
        f"Analytical benchmark context extracted from the session:\n"
        f"{benchmark_context or '(none found)'}"
    )

    system = (
        "You are analysing a figure from a reinforcement learning experiment. "
        "Describe what the plot shows: axes, trends, key numerical values, and "
        "any notable features. Be specific and factual — report only what is "
        "visible in the image. Two to four sentences."
        + benchmark_note
    )
    # Converse image format: raw bytes, no base64 layer. image_raw is
    # bedrock_converse's internal tag telling messages_to_converse to emit
    # {"image": {"format": "png", "source": {"bytes": <raw>}}}.
    messages = [{
        "role": "user",
        "content": [
            {"type": "text", "text": (
                f"Session context (for background only):\n{memory[:2000]}\n\n"
                "Describe this figure based on what you see."
            )},
            {"type": "image_raw", "format": "png", "data": image_bytes},
        ],
    }]

    try:
        description = converse_text(
            client, model, system, messages,
            max_tokens=640, temperature=0.2,
        ).strip()
    except Exception as exc:
        description = f"(Plot description unavailable: {exc})"

    return {"filename": plot_path.name, "label": label, "description": description}


def _describe_plots(
    client, model: str, plot_paths: list[Path], memory: str,
    benchmark_context: str = "",
) -> list[dict]:
    """Describe each plot image in parallel via multimodal LLM calls.

    Returns a list of {filename, label, description} dicts in the same order
    as *plot_paths*.
    """
    if not plot_paths:
        return []

    results = []
    with ThreadPoolExecutor(max_workers=min(len(plot_paths), 4)) as pool:
        futures = {
            pool.submit(_describe_plot, client, model, p, memory, benchmark_context): p
            for p in plot_paths
        }
        for future in as_completed(futures):
            try:
                results.append(future.result())
            except Exception:
                path = futures[future]
                results.append({
                    "filename": path.name,
                    "label": f"fig:{path.stem}",
                    "description": "(Description unavailable)",
                })

    # Preserve the original plot ordering
    name_order = {p.name: i for i, p in enumerate(plot_paths)}
    results.sort(key=lambda r: name_order.get(r["filename"], 999))
    return results


def _tail_lines(path: Path, n: int) -> str:
    """Read the last n lines of a file."""
    try:
        lines = path.read_text().splitlines()
        return "\n".join(lines[-n:])
    except (OSError, UnicodeDecodeError):
        return ""


def _repair_mojibake(text: str) -> str:
    """Best-effort repair for UTF-8 text misread as Latin-1."""
    if not text:
        return ""
    try:
        repaired = text.encode("latin-1").decode("utf-8")
        return repaired if repaired else text
    except UnicodeError:
        return text


def _ascii_fold(text: str) -> str:
    """Fold unicode text to ASCII using NFKD normalization."""
    if not text:
        return ""
    normalized = unicodedata.normalize("NFKD", text)
    return normalized.encode("ascii", "ignore").decode("ascii")


def _normalized_lookup_forms(text: str) -> set[str]:
    """Normalized alphanumeric forms used for fuzzy cite-key matching."""
    forms = set()
    for candidate in {text or "", _repair_mojibake(text or "")}:
        folded = _ascii_fold(candidate).lower()
        cleaned = "".join(ch for ch in folded if ch.isalnum())
        if cleaned:
            forms.add(cleaned)
    return forms


def _make_cite_key(paper: dict) -> str:
    """Generate a BibTeX cite key like 'Ozhamaratli2022' from a paper dict."""
    authors = paper.get("authors", [])
    first_author_raw = str(authors[0]) if authors else "Unknown"
    if "," in first_author_raw:
        surname_raw = first_author_raw.split(",", 1)[0].strip()
    else:
        surname_raw = first_author_raw.split()[-1] if first_author_raw.split() else "Unknown"

    surname = _ascii_fold(_repair_mojibake(surname_raw))
    surname = "".join(ch for ch in surname if ch.isalnum()) or "Unknown"
    year = "".join(ch for ch in str(paper.get("year") or "nd") if ch.isalnum()) or "nd"
    first_author = surname
    return f"{first_author}{year}"


def _generate_bib(papers: list[dict], output_dir: Path) -> list[dict]:
    """Generate references.bib from literature search JSON.

    Returns the papers list augmented with a 'cite_key' field.
    """
    seen_keys = {}
    entries = []
    for paper in papers:
        key = _make_cite_key(paper)
        # Deduplicate keys by appending a/b/c
        if key in seen_keys:
            seen_keys[key] += 1
            key = f"{key}{chr(96 + seen_keys[key])}"  # a, b, c...
        else:
            seen_keys[key] = 1
        paper["cite_key"] = key

        authors_bib = " and ".join(paper.get("authors", ["Unknown"]))
        title = paper.get("title", "Untitled")
        year = paper.get("year") or "n.d."
        url = paper.get("url", "")

        entries.append(
            f"@article{{{key},\n"
            f"  author = {{{authors_bib}}},\n"
            f"  title = {{{title}}},\n"
            f"  year = {{{year}}},\n"
            f"  url = {{{url}}},\n"
            f"}}\n"
        )

    bib_path = output_dir / "references.bib"
    bib_path.write_text("\n".join(entries))
    return papers


_BENCHMARK_KEYWORDS = (
    "benchmark", "analytical", "closed-form", "closed form", "merton",
    "oracle", "optimal policy", "theoretical", "ground truth",
    "baseline solution", "reference solution",
)


def _extract_benchmark_context(
    memory: str, code_snippets: dict[str, str], session_dir: Path,
) -> str:
    """Collect text about analytical benchmarks used in the session.

    Searches memory.md and code files for lines that mention a benchmark
    or closed-form reference, plus math-heavy lines near them. Returns a
    short bundle used when describing plots so the model can name the
    exact relations being plotted.
    """
    snippets: list[str] = []

    def _collect(text: str, source: str) -> None:
        if not text:
            return
        lines = text.splitlines()
        lower_lines = [line.lower() for line in lines]
        keep: set[int] = set()
        for i, lower in enumerate(lower_lines):
            if any(kw in lower for kw in _BENCHMARK_KEYWORDS):
                for j in range(max(0, i - 1), min(len(lines), i + 4)):
                    keep.add(j)
        if not keep:
            return
        picked = [lines[i] for i in sorted(keep)]
        block = "\n".join(picked).strip()
        if block:
            snippets.append(f"# From {source}\n{block}")

    _collect(memory, "memory.md")
    for fname, content in (code_snippets or {}).items():
        _collect(content, f"code/{fname}")

    # Also scan any results/*.md or analysis.md for benchmark discussion.
    for extra in ("analysis.md",):
        p = session_dir / extra
        if p.exists():
            try:
                _collect(p.read_text(), extra)
            except (OSError, UnicodeDecodeError):
                pass

    bundle = "\n\n".join(snippets)
    if len(bundle) > 4000:
        bundle = bundle[:4000] + "\n...(truncated)"
    return bundle


def _gather_context(session_dir: Path) -> dict:
    """Collect all available session artifacts for the report prompt."""
    ctx = {}

    mem_path = session_dir / "memory.md"
    ctx["memory"] = _read_capped(mem_path, _MAX_MEMORY) if mem_path.exists() else ""

    lit_path = session_dir / "references" / "literature_search.md"
    ctx["literature"] = _read_capped(lit_path, _MAX_LITERATURE) if lit_path.exists() else ""

    # Load structured literature data for BibTeX generation
    lit_json_path = session_dir / "references" / "literature_search.json"
    if lit_json_path.exists():
        try:
            ctx["literature_papers"] = json.loads(lit_json_path.read_text())
        except (json.JSONDecodeError, OSError):
            ctx["literature_papers"] = []
    else:
        ctx["literature_papers"] = []

    code_dir = session_dir / "code"
    code_snippets = {}
    if code_dir.exists():
        for fname in _KEY_CODE_FILES:
            fpath = code_dir / fname
            if fpath.exists():
                code_snippets[fname] = _read_capped(fpath, _MAX_CODE_SNIPPET)
    ctx["code_snippets"] = code_snippets

    if code_dir.exists():
        ctx["code_files"] = [f.name for f in sorted(code_dir.iterdir()) if f.is_file()]
    else:
        ctx["code_files"] = []

    log_texts = {}
    if code_dir.exists():
        for log_path in sorted(code_dir.rglob("*.log")):
            log_texts[log_path.name] = _tail_lines(log_path, _MAX_LOG_LINES)
    ctx["training_logs"] = log_texts

    plots = _find_plots(session_dir)
    ctx["plot_paths"] = plots
    ctx["plot_names"] = [p.name for p in plots]

    ctx["artifact"] = gather_artifact_context(session_dir)

    step_texts: dict[str, str] = {}
    for step_path in sorted(session_dir.glob("step_*_conversation.md")):
        label = step_path.stem.replace("step_", "").replace("_conversation", "")
        step_texts[label] = _read_capped(step_path, _MAX_STEP_FILE)
    ctx["step_conversations"] = step_texts

    return ctx


