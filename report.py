# ── Context formatting per section ────────────────────────────────────

def _format_section_context(section: dict, context: dict) -> str:
    """Build the user message for a specific section from its context keys."""
    parts = []

    for key in section["context_keys"]:
        if key == "step_conversations":
            step_texts = context.get("step_conversations") or {}
            requested = section.get("steps") or []
            collected = [(label, step_texts[label]) for label in requested
                         if label in step_texts and step_texts[label]]
            if collected:
                for label, text in collected:
                    parts.append(
                        f"# Design decisions from step {label} conversation\n"
                    )
                    parts.append(text)
                    parts.append("\n\n")
            continue

        if key == "memory" and context.get("memory"):
            parts.append("# Session Decisions (from all 9 steps)\n")
            parts.append(context["memory"])
            parts.append("\n\n")

        elif key == "literature" and context.get("literature"):
            parts.append("# Literature Search Results\n")
            parts.append(context["literature"])
            parts.append("\n\n")

        elif key == "training_logs" and context.get("training_logs"):
            parts.append("# Training Logs (last lines)\n")
            for logname, text in context["training_logs"].items():
                parts.append(f"## {logname}\n```\n{text}\n```\n\n")

        elif key == "plot_descriptions" and context.get("plot_descriptions"):
            parts.append("# Figures (include each one and reference via its label)\n\n")
            for pd in context["plot_descriptions"]:
                parts.append(f"## {pd['filename']}\n")
                parts.append(f"LaTeX label: {pd['label']}\n")
                parts.append(f"Observation: {pd['description']}\n\n")

        elif key == "artifact" and context.get("artifact"):
            art = context["artifact"]
            parts.append(
                "# Shippable Inference Artifact\n"
                f"The trained policy is packaged at `{art['path']}` and is run "
                "with `python solve.py --instance instance.json` (or repeated "
                "`--param k=v`). State this path and invocation in the text so "
                "a reader can run the model, and respect the validity domain "
                "recorded below -- do not claim performance outside it.\n"
                f"Bundle files: {', '.join(art.get('entry_points') or []) or 'n/a'}\n\n"
            )
            if art.get("model_card"):
                parts.append(f"## MODEL_CARD.md\n{art['model_card']}\n\n")
            if art.get("contract"):
                parts.append(
                    f"## contract.json\n```json\n{art['contract']}\n```\n\n"
                )

        elif key == "benchmark_context" and context.get("benchmark_context"):
            parts.append(
                "# Analytical Benchmark Reference\n"
                "When the Results figures compare against an analytical "
                "benchmark, state the exact relation being plotted using the "
                "material below. Do not refer to the benchmark generically.\n"
            )
            parts.append(context["benchmark_context"])
            parts.append("\n\n")

        elif key == "cite_keys" and context.get("cite_keys"):
            parts.append("# Available BibTeX Cite Keys\n")
            parts.append("Use \\cite{key} with ONLY these keys:\n")
            for entry in context["cite_keys"]:
                parts.append(f"- \\cite{{{entry['key']}}} = {entry['title']} ({entry['year']})\n")
            parts.append("\n")

        elif key == "code_snippets_env" and context.get("code_snippets"):
            for fname in ("environment.py",):
                if fname in context["code_snippets"]:
                    parts.append(f"# {fname}\n```python\n{context['code_snippets'][fname]}\n```\n\n")

        elif key == "code_snippets_agent" and context.get("code_snippets"):
            for fname in ("agent.py", "models.py"):
                if fname in context["code_snippets"]:
                    parts.append(f"# {fname}\n```python\n{context['code_snippets'][fname]}\n```\n\n")

        elif key == "code_snippets_config" and context.get("code_snippets"):
            for fname in ("config.py", "train.py"):
                if fname in context["code_snippets"]:
                    parts.append(f"# {fname}\n```python\n{context['code_snippets'][fname]}\n```\n\n")

    return "".join(parts) or "(No additional data available for this section.)"


# ── LLM call ──────────────────────────────────────────────────────────

def _call_llm(client, model: str, system: str, user_content: str) -> str:
    """Single Bedrock Converse call for one section. Returns LaTeX text."""
    messages = [{"role": "user", "content": user_content}]
    full_text = ""
    for _ in range(2):  # one continuation if truncated
        resp = converse_once(
            client, model, system, messages,
            max_tokens=4096, temperature=0.4,
        )
        text = extract_text_from_converse(resp)
        full_text += text

        if resp.get("stopReason") != "max_tokens":
            break

        messages = messages + [
            {"role": "assistant", "content": full_text},
            {"role": "user", "content": "[continue writing from where you left off]"},
        ]

    return full_text


def _generate_section(client, model: str, section: dict, context: dict, output_dir: Path) -> str:
    """Generate one section: call LLM, write .tex file. Returns section name."""
    subsections = section.get("subsections")
    if subsections:
        bodies = []
        for sub in subsections:
            sub_section = {
                "context_keys": sub["context_keys"],
                "steps": sub.get("steps", []),
            }
            user_content = _format_section_context(sub_section, context)
            bodies.append(_call_llm(client, model, sub["system"], user_content))
        latex_body = "\n\n".join(bodies)
    else:
        user_content = _format_section_context(section, context)
        latex_body = _call_llm(client, model, section["system"], user_content)

    # Wrap with \section{} heading
    tex_content = f"\\section{{{section['heading']}}}\n\n{latex_body}\n"
    (output_dir / section["filename"]).write_text(tex_content)

    return section["name"]


# ── LaTeX rendering ───────────────────────────────────────────────────

def _collect_known_labels(output_dir: Path) -> set[str]:
    """Collect LaTeX labels from generated section files and optional aux file."""
    known_labels: set[str] = set()
    label_pattern = re.compile(r"\\label\{([^{}]+)\}")
    aux_pattern = re.compile(r"\\newlabel\{([^{}]+)\}")

    for section in SECTIONS:
        section_path = output_dir / section["filename"]
        if not section_path.exists():
            continue
        try:
            text = section_path.read_text()
        except (OSError, UnicodeDecodeError):
            continue
        known_labels.update(label_pattern.findall(text))

    aux_path = output_dir / "main.aux"
    if aux_path.exists():
        try:
            aux_text = aux_path.read_text()
            known_labels.update(aux_pattern.findall(aux_text))
        except (OSError, UnicodeDecodeError):
            pass

    return known_labels


def _resolve_cite_key(raw_key: str, canonical_keys: set[str], lookup_map: dict[str, str]) -> str | None:
    """Resolve a raw cite key to a canonical key, tolerant to encoding/case drift."""
    key = raw_key.strip()
    if not key:
        return None
    if key in canonical_keys:
        return key

    for form in _normalized_lookup_forms(key):
        resolved = lookup_map.get(form)
        if resolved:
            return resolved
    return None


def _infer_ref_fallback(command: str, label: str, text: str, pos: int) -> str:
    """Infer readable fallback text for unresolved LaTeX references."""
    if command == "eqref":
        return "the equation"

    prefix = label.split(":", 1)[0].strip().lower() if ":" in label else label.strip().lower()
    by_prefix = {
        "fig": "the figure",
        "figure": "the figure",
        "tab": "the table",
        "tbl": "the table",
        "table": "the table",
        "sec": "the section",
        "section": "the section",
        "subsec": "the section",
        "eq": "the equation",
        "equation": "the equation",
    }
    if prefix in by_prefix:
        return by_prefix[prefix]

    # Use local prose hints when label prefixes are absent/nonstandard.
    window = text[max(0, pos - 32):pos].lower()
    if "figure" in window:
        return "the figure"
    if "table" in window:
        return "the table"
    if "section" in window:
        return "the section"
    if "equation" in window or "eq." in window:
        return "the equation"

    return "the relevant item"


def _cleanup_generated_sections(output_dir: Path, cite_keys: list[dict]) -> None:
    """Canonicalize cite commands and replace unresolved refs in generated sections."""
    canonical_list = [str(entry.get("key", "")).strip() for entry in cite_keys if entry.get("key")]
    canonical_keys = set(canonical_list)
    lookup_map: dict[str, str] = {}
    for key in canonical_list:
        for form in _normalized_lookup_forms(key):
            lookup_map.setdefault(form, key)

    known_labels = _collect_known_labels(output_dir)

    cite_pattern = re.compile(
        r"\\(cite|citep|citet)(\*?)(\s*\[[^\]]*\])?(\s*\[[^\]]*\])?\s*\{([^{}]*)\}"
    )
    ref_pattern = re.compile(r"\\(ref|autoref|eqref)\s*\{([^{}]+)\}")
    duplicate_phrase_pattern = re.compile(
        r"\b(Figure|Table|Section|Equation)~the (figure|table|section|equation)\b"
    )

    for section in SECTIONS:
        section_path = output_dir / section["filename"]
        if not section_path.exists():
            continue

        try:
            text = section_path.read_text()
        except (OSError, UnicodeDecodeError):
            continue

        def _replace_cite(match: re.Match) -> str:
            command, star, opt1, opt2, raw_keys = match.groups()
            resolved_keys = []
            seen = set()
            for raw_key in raw_keys.split(","):
                resolved = _resolve_cite_key(raw_key, canonical_keys, lookup_map)
                if resolved and resolved not in seen:
                    seen.add(resolved)
                    resolved_keys.append(resolved)

            if not resolved_keys:
                return ""

            options = f"{opt1 or ''}{opt2 or ''}"
            return f"\\{command}{star}{options}" + "{" + ",".join(resolved_keys) + "}"

        def _replace_ref(match: re.Match) -> str:
            command, label = match.groups()
            if label in known_labels:
                return match.group(0)
            return _infer_ref_fallback(command, label, text, match.start())

        rewritten = cite_pattern.sub(_replace_cite, text)
        rewritten = ref_pattern.sub(_replace_ref, rewritten)
        rewritten = duplicate_phrase_pattern.sub(
            lambda m: f"the {m.group(2)}" if m.group(1).lower() == m.group(2).lower() else m.group(0),
            rewritten,
        )
        rewritten = re.sub(r"[ \t]+([,.;:])", r"\1", rewritten)
        rewritten = re.sub(r"[ \t]{2,}", " ", rewritten)
        rewritten = re.sub(r"[ \t]+\n", "\n", rewritten)
        rewritten = re.sub(r"\n{3,}", "\n\n", rewritten)

        if rewritten != text:
            section_path.write_text(rewritten)


def _emit_unresolved_warnings(output_dir: Path) -> None:
    """Print explicit unresolved-citation/reference warnings from LaTeX logs."""
    unresolved_cites = set()
    unresolved_refs = set()

    log_path = output_dir / "main.log"
    if log_path.exists():
        try:
            log_text = log_path.read_text()
        except (OSError, UnicodeDecodeError):
            log_text = ""
        unresolved_cites.update(re.findall(r"LaTeX Warning: Citation [`']([^`']+)[`'].*undefined", log_text))
        unresolved_refs.update(re.findall(r"LaTeX Warning: Reference [`']([^`']+)[`'].*undefined", log_text))

    blg_path = output_dir / "main.blg"
    if blg_path.exists():
        try:
            blg_text = blg_path.read_text()
        except (OSError, UnicodeDecodeError):
            blg_text = ""
        unresolved_cites.update(re.findall(r'database entry for "([^"]+)"', blg_text))

    if unresolved_cites:
        ordered = ", ".join(sorted(unresolved_cites))
        print(f"  \033[33m[Unresolved citations: {ordered}]\033[0m")
    if unresolved_refs:
        ordered = ", ".join(sorted(unresolved_refs))
        print(f"  \033[33m[Unresolved references: {ordered}]\033[0m")


def _generate_title(client, model: str, memory: str) -> str:
    """Use the LLM to generate an academic paper title from session decisions."""
    try:
        title = converse_text(
            client, model,
            "Generate a concise (no more than 8-10 words) academic paper title for a reinforcement learning "
            "study. The title should be specific to the problem domain and approach "
            "described. Return ONLY the title text, no quotes, no explanation, "
            "no LaTeX commands.",
            [{"role": "user", "content": memory or "(No data)"}],
            max_tokens=100, temperature=0.3,
        ).strip().strip('"\'')
        if title:
            return title
    except Exception:
        pass
    return "Reinforcement Learning System Design Report"


def _render_main_tex(
    title: str,
    plot_paths: list[Path],
    output_dir: Path,
    template_dir: Path,
) -> Path | None:
    """Render main.tex from template, copy plots, and compile to PDF."""
    output_dir.mkdir(parents=True, exist_ok=True)

    # Copy plot files so pdflatex can find them
    for plot in plot_paths:
        dest = output_dir / plot.name
        if not dest.exists():
            shutil.copy2(plot, dest)

    # report_template.tex includes this project-owned description with a
    # relative path, so stage it with the generated report inputs.
    description = template_dir / "templates" / "carl_description.tex"
    if description.is_file():
        shutil.copy2(description, output_dir / description.name)

    # Render main.tex from template
    env = Environment(
        loader=FileSystemLoader(str(template_dir)),
        variable_start_string="(((",
        variable_end_string=")))",
        block_start_string="((*",
        block_end_string="*))",
        comment_start_string="((#",
        comment_end_string="#))",
    )
    template = env.get_template("report_template.tex")
    rendered = template.render(
        title=title,
        date=datetime.now().strftime("%B %d, %Y"),
    )

    main_tex = output_dir / "main.tex"
    main_tex.write_text(rendered)

    # Compile: pdflatex -> bibtex -> pdflatex -> pdflatex
    pdflatex = shutil.which("pdflatex")
    if not pdflatex:
        print("  \033[33m[pdflatex not found -- attempting to install texlive...]\033[0m")
        try:
            subprocess.run(["sudo", "apt-get", "update", "-qq"], check=True, timeout=120)
            subprocess.run(
                ["sudo", "apt-get", "install", "-y", "-qq",
                 "texlive", "texlive-latex-recommended"],
                check=True, timeout=300,
            )
            pdflatex = shutil.which("pdflatex")
        except Exception as e:
            print(f"  \033[31m[texlive install failed: {e}]\033[0m")
        if not pdflatex:
            print("  \033[33m[.tex files saved but PDF not generated.]\033[0m")
            return None

    run_args = dict(cwd=str(output_dir), capture_output=True, text=True, timeout=120)

    # First pdflatex pass (generates .aux for bibtex)
    subprocess.run([pdflatex, "-interaction=nonstopmode", "-halt-on-error", "main.tex"], **run_args)

    # BibTeX pass (resolves citations)
    bibtex = shutil.which("bibtex")
    if bibtex and (output_dir / "references.bib").exists():
        subprocess.run([bibtex, "main"], **run_args)

    # Two more pdflatex passes (resolve cross-references and citation numbers)
    for _ in range(2):
        result = subprocess.run(
            [pdflatex, "-interaction=nonstopmode", "-halt-on-error", "main.tex"], **run_args,
        )

    _emit_unresolved_warnings(output_dir)

    pdf_path = output_dir / "main.pdf"
    if pdf_path.exists():
        return pdf_path

    # PDF compilation failed
    log_path = output_dir / "main.log"
    if log_path.exists():
        print(f"  \033[33m[pdflatex failed -- see {log_path} for details]\033[0m")
    else:
        print(f"  \033[33m[pdflatex failed: {result.stderr[:300]}]\033[0m")
    return None


# ── Main entry point ──────────────────────────────────────────────────

def generate_report(session, client, model: str) -> Path | None:
    """Generate a LaTeX + PDF report for a completed CARL session.

    Each section is generated by a parallel LLM call, written to its own
    .tex file, and assembled via \\input{} in main.tex.

    Returns:
        Path to the generated PDF, or None on failure.
    """
    session_dir = session.session_dir if hasattr(session, "session_dir") else Path(session)

    try:
        context = _gather_context(session_dir)
        output_dir = session_dir / "results"
        output_dir.mkdir(parents=True, exist_ok=True)

        # Generate references.bib and populate cite_keys in context
        if context["literature_papers"]:
            papers = _generate_bib(context["literature_papers"], output_dir)
            context["cite_keys"] = [
                {"key": p["cite_key"], "title": p["title"], "year": p.get("year", "n.d.")}
                for p in papers
            ]
        else:
            context["cite_keys"] = []

        # Extract any analytical benchmark context so plot descriptions
        # state the exact relation being plotted (not just "benchmark").
        context["benchmark_context"] = _extract_benchmark_context(
            context["memory"], context["code_snippets"], session_dir,
        )

        # Describe each plot via multimodal LLM calls (before section gen)
        if context["plot_paths"]:
            print(f"  Describing {len(context['plot_paths'])} plots...")
            context["plot_descriptions"] = _describe_plots(
                client, model, context["plot_paths"], context["memory"],
                benchmark_context=context["benchmark_context"],
            )
        else:
            context["plot_descriptions"] = []

        # Generate all sections in parallel
        print(f"  Generating {len(SECTIONS)} sections in parallel...")
        with ThreadPoolExecutor(max_workers=len(SECTIONS)) as pool:
            futures = {
                pool.submit(_generate_section, client, model, sec, context, output_dir): sec["name"]
                for sec in SECTIONS
            }
            for future in as_completed(futures):
                name = futures[future]
                try:
                    future.result()
                    print(f"    {name} done")
                except Exception as e:
                    print(f"    \033[33m{name} failed: {e}\033[0m")
                    # Write a placeholder so main.tex still compiles
                    sec = next(s for s in SECTIONS if s["name"] == name)
                    (output_dir / sec["filename"]).write_text(
                        f"\\section{{{sec['heading']}}}\n\n"
                        f"(Section generation failed: {e})\n"
                    )

        _cleanup_generated_sections(output_dir, context["cite_keys"])

        # Render main.tex and compile to PDF
        title = _generate_title(client, model, context["memory"])
        template_dir = Path(__file__).resolve().parent
        pdf_path = _render_main_tex(title, context["plot_paths"], output_dir, template_dir)
        return pdf_path

    except Exception as e:
        print(f"  \033[31m[Report generation failed: {e}]\033[0m")
        return None


# ── Standalone usage ──────────────────────────────────────────────────

if __name__ == "__main__":
    import os
    import sys

    if len(sys.argv) < 2:
        print("Usage: python report.py <session_directory>")
        print("Example: python report.py sessions/portfolio_opt_20260406-1430/")
        sys.exit(1)

    session_dir = Path(sys.argv[1])
    if not session_dir.is_dir():
        print(f"Error: {session_dir} is not a directory")
        sys.exit(1)

    # Reuse the same client setup as chat.py / web.py
    from chat import _load_dotenv, _build_bedrock_client
    from bedrock_models import DEFAULT_REPORT_MODEL

    carl_dir = str(Path(__file__).resolve().parent)
    _load_dotenv(carl_dir)

    region = os.environ.get("AWS_REGION", "us-west-2")
    bedrock_client = _build_bedrock_client(region)
    # Report writing has its own model role (Sonnet 5 by default). No startup
    # probe: resolve_model_id only probes the main default, and anything else
    # is trusted as an explicit choice.
    model_id = os.environ.get("CARL_REPORT_MODEL", DEFAULT_REPORT_MODEL)

    print(f"  Generating report for session: {session_dir}")
    result = generate_report(session_dir, bedrock_client, model_id)
    if result:
        print(f"  Report saved: {result}")
    else:
        tex = session_dir / "results" / "main.tex"
        if tex.exists():
            print(f"  LaTeX source saved: {tex} (PDF compilation failed)")
        else:
            print("  Report generation failed.")
